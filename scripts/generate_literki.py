#!/usr/bin/env python3
"""Generate the game's C/browser vocabulary and the ElevenLabs recording list."""
import csv
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'assets/games/literki/words.json'


def save(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def generate():
    data = json.loads(DATA.read_text())
    groups = data['groups']
    words = []
    for group in groups:
        assert len(group['words']) == 3, group['letter']
        for word in group['words']:
            assert word['word'][0].upper() == group['letter']
            assert 0 < len(word['word']) <= 16
            assert word['id'].isascii() and word['id'].replace('_', '').isalnum()
            words.append(dict(word, letter=group['letter']))
    assert len({w['id'] for w in words}) == len(words)
    assert {'mama', 'tata', 'dom'} <= {w['word'] for w in words}
    quote = lambda s: json.dumps(s, ensure_ascii=False)
    source = ['/* Generated by scripts/generate_literki.py from words.json. */',
              'const letters_word_t letters_words[] = {']
    for w in words:
        source.append('    {' + ', '.join(quote(w[k]) for k in ('id', 'word')) + ', ' + quote(w['word'].upper()) + ', ' + quote(w['letter']) + '},')
    source += ['};', f'const unsigned letters_word_count = {len(words)}u;',
               'const char letters_alphabet[][4] = {' + ','.join(quote(g['letter']) for g in groups) + '};',
               f'const unsigned letters_alphabet_count = {len(groups)}u;']
    save(ROOT / 'src/letters_data.inc', '\n'.join(source) + '\n')
    browser = {'groups': groups, 'words': words, 'alphabet': [g['letter'] for g in groups], 'audioFiles': sorted(p.name for p in (ROOT / 'assets/games/literki/audio').glob('*.mp3'))}
    save(ROOT / 'assets/literki-data.js', '// Generated from games/literki/words.json.\nwindow.literkiData = ' + json.dumps(browser, ensure_ascii=False) + ';\n')
    rows = [
        ('welcome.mp3', 'Cześć! Pobawmy się literkami. Posłuchaj i wybierz odpowiedź.', 'Powitanie'),
        ('read.mp3', 'Przeczytaj wyraz i wybierz pasujący obrazek.', 'Czytanie: nigdy nie czytaj wyrazu z zadania'),
        ('again.mp3', 'Spróbuj jeszcze raz. Dasz radę!', 'Pomyłka: łagodnie, bez smutnego tonu'),
        ('bravo.mp3', 'Brawo! Świetnie ci poszło!', 'Pochwała'),
    ]
    for w in words:
        rows.append((f'first_{w["id"]}.mp3', f'Jaką literką zaczyna się słowo: {w["word"]}?', 'Obrazek → pierwsza litera'))
        rows.append((f'spell_{w["id"]}.mp3', f'Ułóż z literek słowo: {w["word"]}.', 'Układanie wyrazu'))
    for i, g in enumerate(groups):
        rows.append((f'letter_{i:02}.mp3', f'Wybierz obrazek na literę {g["letter"]}.', 'Litera → obrazek; wypowiedz polską nazwę litery'))
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(['plik', 'tekst', 'uwagi'])
    writer.writerows(rows)
    save(ROOT / 'docs/games/elevenlabs.csv', out.getvalue())
    save(ROOT / 'docs/games/teksty-do-nagran.txt', '\n\n'.join(f'{file}\n{text}' for file, text, _ in rows) + '\n')
    return len(groups), len(words), len(rows)


if __name__ == '__main__':
    print('Literki: %d liter, %d obrazków, %d nagrań' % generate())
